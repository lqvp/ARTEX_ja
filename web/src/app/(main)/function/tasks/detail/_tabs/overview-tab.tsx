type Translate = ReturnType<typeof useTranslations>;

// Compact token count (12345 → 12.3k, 2000000 → 2M).
function fmtTokens(n: number): string {
  if (n >= 1_000_000) return (n / 1_000_000).toFixed(n >= 10_000_000 ? 0 : 1) + "M";
  if (n >= 1000) return (n / 1000).toFixed(n >= 10000 ? 0 : 1) + "k";
  return String(n);
}

// Cache hit rate = cache reads / input (InputTokens already includes the cache_read
// subset, so the ratio stays within 0–100%).
function cacheHitRate(cacheRead: number, input: number): string {
  if (input <= 0) return "—";
  return Math.round((cacheRead / input) * 100) + "%";
}

// Display value for one test-scope row: domain / CIDR / company.
function scopeValue(row: TaskScopeRow, t: Translate): string {
  if (row.value) return row.value;
  if (row.domain) return row.domain;
  if (row.net) return row.net;
  if (row.company_id) return row.company_name?.trim() ? row.company_name : t("companyFallback", { id: row.company_id });
  return "—";
}

