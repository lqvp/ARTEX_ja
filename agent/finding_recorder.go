package agent

import (
	"context"

	"github.com/Autumn-27/artex/db"
)

// FindingRecorder is injected by the host; agents never synthesize or copy
// evidence bodies themselves. Its implementation owns the atomic write.
type FindingRecorder interface {
	Record(context.Context, db.RecordFindingInput, []db.TrafficRef) (*db.RecordedFinding, error)
}

// Tool-use guidance is appended without replacing the user's editable prompt.
// It does not require capture or claim that unavailable traffic tools exist.
const findingTrafficGuidance = "\n\n**Vulnerability traffic evidence (optional)**: when calling report_finding to report a vulnerability, if you have already inspected HTTP request/response pairs confirmed to support the finding's conclusion, you may bind their real IDs via traffic_refs in reproduction order; domains and timestamps only narrow candidates and do not establish association. For non-HTTP vulnerabilities such as TCP, or when nothing was captured or no exact match exists, omit traffic_refs or pass []; keep other verifiable evidence (command output, logs, etc.) in evidence, and state why nothing was bound. Do not guess IDs, and do not re-run probes only to pad the evidence bundle."

func (t *ToolSet) SetFindingRecorder(r FindingRecorder)   { t.findingRecorder = r }
func (w *Worker) SetFindingRecorder(r FindingRecorder)    { w.findingRecorder = r }
func (p *Planner) SetFindingRecorder(r FindingRecorder)   { p.findingRecorder = r }
func (m *MainAgent) SetFindingRecorder(r FindingRecorder) { m.findingRecorder = r }
